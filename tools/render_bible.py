a(''); a('## 十一、认知边界总表'); a('写对白后，检查脚本用这张表找「不该知道的人说出了这件事」和「把事说错了」的台词。'+b.get('facts_note','')+'。'); a('')
a('| 事 | 关键词 | 一开始就知道 | 谁、什么时候知道 | 从哪起公开 | 备注 |'); a('|---|---|---|---|---|---|')
for f in b['facts']:
    lc='；'.join(f"{names.get(k,'所有人' if k=='all' else k)}：{v}" for k,v in f['learn_ch'].items())
    pub=f"第 {f['public_after_ch']} 章" if f['public_after_ch'] else ('任务 '+'、'.join(f['public_after_node']) if f['public_after_node'] else '一直是秘密')
    note=f['note']+(f"；说错的词：{'、'.join(f['misnomers'])}" if f.get('misnomers') else '')
    a(f"| {f['what']} | {'、'.join(f['keywords'])} | {'、'.join(names.get(k,k) for k in f['known_by'])} | {lc} | {pub} | {note} |")
