a('**每个人的下场**：'); a(''); a('| 人物 | 规则 |'); a('|---|---|')
for f in es['fates']: a(f"| {names.get(f['who'],f['who'])} | {'<br>'.join(f['rules'])} |")
a(''); a('## 九、认知边界'); a('')
a('每个人知道什么、怀疑什么、不知道什么、误以为什么、绝不会说什么；带 D / S 编号的，看你在那次决定里选了什么。'); a('')
