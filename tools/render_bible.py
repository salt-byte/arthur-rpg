for c in main:
    a(f"### {c['name']} · {c['role']}"); a('')
    a(f"**一句话**：{c['one_line']}"); a('')
    a(f"**行为逻辑**：{c['logic']}"); a(''); a(f"**要什么**：{c['wants']}"); a(''); a(f"**命门**：{c['weakness']}"); a('')
    a('**阻碍**：'); a(f"- 内在：{c['obstacle']['inner']}"); a(f"- 外在：{c['obstacle']['outer']}"); a('')
    a('**弧线**：'); a(f"- 开始时：{c['arc']['start']}"); a(f"- 中段转折：{c['arc']['turn']}"); a(f"- 结束时：{c['arc']['end']}"); a('')
    a(f"**独立生活**：{c['independent_life']}"); a('')
    a(f"**说话方式**：{c['voice']}。绝不说：{'；'.join(c['never_says'])}。"); a('')
    a(f"**识别细节**：{c['detail']}"); a(''); a(f"出场章节：{j(c['appears_in'])}。出处：{c['source']}"); a('')
