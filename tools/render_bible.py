    kn=b['player']['knowledge'] if cid=='player' else next(c['knowledge'] for c in b['characters'] if c['id']==cid)
    a(f"### {names[cid]}")
    for lab,key in [('知道','knows'),('怀疑','suspects'),('不知道','doesnt_know'),('误以为','misbelieves'),('绝不会说','never_says')]:
        if kn[key]: a(f"- **{lab}**：{'；'.join(kn[key])}")
    a('')
