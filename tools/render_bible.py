a(''); a('## 三、因果主线'); a('')
a('每个转折按「新的压力 → 谁解读它 → 他选了什么方法 → 改变了谁的选项 → 可见的后果」写。'); a('')
for s in b['causal_spine']: a(f"**{s['step']}**：{s['text']}"); a('')
pk=b['packs'][0]
a('## 四、6 章梗概'); a(''); a(pk['note']); a('')
for c in pk['chapters']:
    a(f"### 第 {c['n']} 章 · {c['title']}（{c['job']}）"); a('')
    if c.get('note'): a(f"**时间**：{c['note']}"); a('')
    a(f"**你为什么在这**：{c['why_player_here']}"); a(''); a('**必须发生的事**：')
    for m in c['must_happen']: a(f'- {m}')
    a('')
    if c.get('vision'): a(f"**你在这章看见的将来**：{c['vision']}"); a('')
    if c.get('setback'): a(f"**受挫在哪**：{c['setback']}"); a('')
    if c.get('reward'): a(f"**回报**：{c['reward']}"); a('')
    a(f"**出场**：{'、'.join(names.get(x,x) for x in c['cast'])}"); a('')
    a(f"**不可逆的事**：{c['irreversible']}"); a(''); a(f"**章末钩子**（强度 {c['hook_strength']}/5）：{c['hook']}"); a('')
    a(f"出处：{j(c['sources'])}"); a('')
