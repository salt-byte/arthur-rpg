a('第一到六节是上半：世界与故事（A0 已通过）。第七节起是下半：你在每章做的决定、结局、每个人什么时候知道什么、伏笔。'); a('')
a('## 先看这里'); a('')
a(f"**一句话故事**：{b['logline']}"); a('')
a(f"**中心张力**：{b['central_tension']}"); a('')
