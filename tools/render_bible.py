for d in b['decisions']:
    if d['kind']=='ending': continue
    tag='主线' if d['kind']=='main' else f"支线「{d['side']}」"
    a(f"### 第 {d['ch']} 章 · {tag}（{d['id']}）"); a('')
    if d.get('summary'): a(f"**这条支线讲什么**：{d['summary']}（出处：{d['source']}）"); a('')
    a(f"**你看见的**：{d['vision']}"); a(''); a(f"**在哪决定**：{d['where']}"); a('')
    a('| 选项 | 局势怎么变 | 之后谁提起 |'); a('|---|---|---|')
    for o in d['options']:
        rb='；'.join(f"第 {r['ch']} 章，{names.get(r['who'],r['who'])}：{r['what']}" for r in o['readback'])
        a(f"| **{o['id']}** {o['text']} | {o['effect']} | {rb} |")
    a('')
