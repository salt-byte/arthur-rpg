a(''); a('### 势力'); a('| 势力 | 要什么 | 怕什么 | 默认怎么对你 |'); a('|---|---|---|---|')
for f in b['factions']: a(f"| {f['name']} | {f['wants']} | {f['fears']} | {f['default_toward_player']} |")
a(''); a('### 地点'); a('| 地点 | 有谁 | 有什么 | 通向 | 危险 | 章 | 出处 |'); a('|---|---|---|---|---|---|---|')
for l in b['locations']: a(f"| {l['name']} | {l['who']} | {l['what']} | {j(l['leads_to']) or '—'} | {l['danger']} | {j(l['chapters'])} | {l['source']} |")
a(''); a('### 硬约束')
for h in b['hard_constraints']: a(f'- {h}')
a(''); a('## 二、人物卡'); a('')
pl=b['player']
a('### 学徒（你）· 主角'); a('')
a(f"**一句话**：{pl['one_line']}"); a(''); a('**处境**：')
for x in pl['position']: a(f'- {x}')
a(''); a(f"**要什么**：{pl['wants']}"); a(''); a(f"**命门**：{pl['weakness']}"); a('')
a('**阻碍**：'); a(f"- 内在：{pl['obstacle']['inner']}"); a(f"- 外在：{pl['obstacle']['outer']}"); a('')
