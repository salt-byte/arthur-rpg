for k,v in b.get('lower_half_tuning',{}).items(): a(f"- {k}：{v}")
a('')
a('## 一、世界观'); a(''); a('### 世界硬规则'); a('后面所有剧情都不能违反这几条。'); a('')
a('| # | 规则 | 代价 | 为什么重要 | 出处 |'); a('|---|---|---|---|---|')
